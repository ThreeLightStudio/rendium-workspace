export type TranslationKey = keyof typeof MESSAGES.en;

const listeners = new Set<() => void>();

let currentLocale: Locale = resolveInitialLocale();

function resolveInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'ko';
  }

  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'ko' || stored === 'en') {
    return stored;
  }

  const browserLocale = window.navigator.language.toLowerCase();
  return browserLocale.startsWith('ko') ? 'ko' : 'en';
}

function persistLocale(locale: Locale): void {
  if (typeof window === 'undefined') {
    return;
  }

  window.localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
}

function notify(): void {
  for (const listener of listeners) {
    listener();
  }
}

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  if (locale === currentLocale) {
    return;
  }

  currentLocale = locale;
  persistLocale(locale);
  notify();
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function translate(
  key: TranslationKey,
  vars?: TranslationVars,
  locale: Locale = currentLocale,
): string {
  const template = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  if (!vars) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function formatNumber(value: number, locale: Locale = currentLocale): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatDateTime(
  value: number | Date,
  options: Intl.DateTimeFormatOptions = {
    dateStyle: 'medium',
    timeStyle: 'short',
  },
  locale: Locale = currentLocale,
): string {
  return new Intl.DateTimeFormat(locale === 'ko' ? 'ko-KR' : 'en-US', options).format(
    typeof value === 'number' ? new Date(value) : value,
  );
}

export function formatTimeOfDay(value: number | Date, locale: Locale = currentLocale): string {
  return new Intl.DateTimeFormat(locale === 'ko' ? 'ko-KR' : 'en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).format(typeof value === 'number' ? new Date(value) : value);
}

type LocaleContextValue = {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: typeof translate;
  formatDateTime: typeof formatDateTime;
  formatTimeOfDay: typeof formatTimeOfDay;
  formatNumber: typeof formatNumber;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, getLocale);

  useEffect(() => {
    persistLocale(locale);
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, vars) => translate(key, vars, locale),
      formatDateTime: (value, options) => formatDateTime(value, options, locale),
      formatTimeOfDay: (value) => formatTimeOfDay(value, locale),
      formatNumber: (value) => formatNumber(value, locale),
    }),
    [locale],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error('useLocale must be used inside <LocaleProvider>');
  }

  return context;
}
